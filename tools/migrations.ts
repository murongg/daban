import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { type MigrationMeta, readMigrationFiles } from 'drizzle-orm/migrator';

const root = fileURLToPath(new URL('..', import.meta.url));
const engine = path.join(root, 'packages/engine');
export const stores = [
  'attachments',
  'budgets',
  'chats',
  'commands',
  'connections',
  'groups',
  'integrations',
  'knowledge',
  'notes',
  'remote',
  'projects',
  'schedules',
  'skills',
  'tab-store',
  'transcripts',
  'work',
] as const;
type Store = (typeof stores)[number];

const schema = (store: Store) => path.join(engine, 'src', `${store}-schema.ts`);
const folder = (store: Store) => path.join(engine, 'drizzle', store);
// drizzle-kit treats --schema as a glob, so Windows paths must be relative with forward slashes.
const posix = (file: string) => path.relative(root, file).split(path.sep).join('/');
const embedded = (store: Store) => path.join(engine, 'src', `${store}-migrations.ts`);

function store(name: string | undefined): Store {
  const found = stores.find((item) => item === name);
  if (!found) throw new Error(`Unknown store "${name}". Expected one of: ${stores.join(', ')}`);
  return found;
}

const scripts = {
  biome: 'node_modules/@biomejs/biome/bin/biome',
  'drizzle-kit': 'node_modules/drizzle-kit/bin.cjs',
};

// Windows refuses to spawn .cmd shims without a shell, so run the JS entry points with node.
function run(name: keyof typeof scripts, args: string[], options: { stdio?: 'inherit' } = {}) {
  return execFileSync(process.execPath, [path.join(root, scripts[name]), ...args], {
    cwd: root,
    encoding: 'utf8',
    ...options,
  });
}

function read(item: Store): MigrationMeta[] {
  return readMigrationFiles({ migrationsFolder: folder(item) });
}

async function embed(items: readonly Store[]) {
  const files: string[] = [];
  for (const item of items) {
    if (!existsSync(folder(item))) continue;
    const text = `// Generated by tools/migrations.ts from packages/engine/drizzle/${item}. Do not edit.
import type { Migration } from './database.js';

export const migrations: Migration[] = ${JSON.stringify(read(item), null, 2)};
`;
    await writeFile(embedded(item), text);
    files.push(embedded(item));
  }
  if (files.length) run('biome', ['format', '--write', ...files], { stdio: 'inherit' });
}

async function check() {
  const issues: string[] = [];
  for (const item of stores) {
    if (!existsSync(schema(item))) {
      issues.push(`${item}: missing ${path.relative(root, schema(item))}`);
      continue;
    }
    if (!existsSync(embedded(item))) {
      issues.push(`${item}: missing ${path.relative(root, embedded(item))}`);
      continue;
    }
    const module: { migrations: MigrationMeta[] } = await import(
      pathToFileURL(embedded(item)).href
    );
    try {
      assert.deepEqual(module.migrations, read(item));
    } catch {
      issues.push(`${item}: embedded migrations are stale; run npm run db:embed`);
    }
    const plan = run('drizzle-kit', [
      'generate',
      '--dialect',
      'sqlite',
      '--schema',
      posix(schema(item)),
      '--out',
      posix(folder(item)),
      '--explain',
      '--output',
      'json',
    ]);
    if (JSON.parse(plan).status !== 'no_changes')
      issues.push(`${item}: schema has changes without a migration; run npm run db:generate`);
  }
  if (issues.length) {
    console.error(issues.join('\n'));
    process.exitCode = 1;
  } else console.log(`Database migrations: ${stores.length} stores match their schemas.`);
}

const [command, name, label] = process.argv.slice(2);
if (command === 'generate') {
  const item = store(name);
  run(
    'drizzle-kit',
    [
      'generate',
      '--dialect',
      'sqlite',
      '--schema',
      posix(schema(item)),
      '--out',
      posix(folder(item)),
      ...(label ? ['--name', label] : []),
    ],
    { stdio: 'inherit' },
  );
  await embed([item]);
} else if (command === 'embed') await embed(name ? [store(name)] : stores);
else if (command === 'check') await check();
else {
  console.error('Usage: tools/migrations.ts generate <store> [name] | embed [store] | check');
  process.exitCode = 1;
}
